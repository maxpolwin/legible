// Turns build-fonts/ (see scripts/build-fonts.sh) into src/lib/bundledfonts.generated.ts.
// With no build-fonts/ it writes an empty stub, so `npm run build` still works
// (the plugin then simply has no built-in fonts). Output is gitignored.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = join(root, 'build-fonts')
const out = join(root, 'src', 'lib', 'bundledfonts.generated.ts')
const HEADER = '// GENERATED by scripts/gen-bundled.mjs — do not edit or commit.\n'
const MAX_FILE_BYTES = 400_000 // sanity cap: subsetted Latin fonts are ~30-80 KB

if (!existsSync(join(srcDir, 'manifest.json'))) {
  writeFileSync(out, `${HEADER}export const BUNDLED_INDEX: ReadonlyArray<BundledIndexEntry> = []\nexport const BUNDLED_DATA: Readonly<Record<string, string>> = {}\n${TYPE()}`)
  console.log('gen-bundled: no build-fonts/ — wrote an empty stub (run `npm run fonts` for built-in fonts)')
  process.exit(0)
}

const manifest = JSON.parse(readFileSync(join(srcDir, 'manifest.json'), 'utf8'))
const index = []
const data = {}
for (const m of manifest) {
  // File names come from our own build, but never trust a path: plain names only.
  if (!/^[A-Za-z0-9-]+\.ttf$/.test(m.file)) throw new Error(`bad font file name: ${m.file}`)
  const bytes = readFileSync(join(srcDir, m.file))
  if (bytes.length === 0 || bytes.length > MAX_FILE_BYTES) throw new Error(`unexpected size for ${m.file}: ${bytes.length}`)
  index.push({ file: m.file, family: m.family, style: m.style, postscriptName: m.postscriptName, fsType: m.fsType })
  data[m.file] = bytes.toString('base64')
}
writeFileSync(
  out,
  `${HEADER}export const BUNDLED_INDEX: ReadonlyArray<BundledIndexEntry> = ${JSON.stringify(index)}\nexport const BUNDLED_DATA: Readonly<Record<string, string>> = ${JSON.stringify(data)}\n${TYPE()}`
)
console.log(`gen-bundled: ${index.length} fonts, ${(Object.values(data).join('').length / 1e6).toFixed(2)} MB base64`)

function TYPE() {
  return 'interface BundledIndexEntry {\n  file: string\n  family: string\n  style: string\n  postscriptName: string\n  fsType: number\n}\n'
}
